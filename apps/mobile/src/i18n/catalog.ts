export function deviceLanguage(): LanguageCode {
  try {
    const loc = Intl.DateTimeFormat().resolvedOptions().locale || "";
    const code = loc.slice(0, 2).toLowerCase();
    if (code === "nb" || code === "nn") return "no";
    if (isLanguageCode(code)) return code;
  } catch {
    /* ignore */
  }
  return "he";
}

export function translateMsg(lang: LanguageCode, key: MsgKey, vars?: Record<string, string>) {
  const raw = CATALOG[lang]?.[key] || CATALOG.en[key] || CATALOG.he[key] || key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, value), raw);
}

export function isRtlLang(lang: LanguageCode) {
  return LANGUAGE_BY_CODE[lang]?.rtl === true;
}
